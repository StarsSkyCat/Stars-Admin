-- 持久会话版本防止 Redis 撤销失败或进程重启后旧令牌恢复。
ALTER TABLE sys_user ADD COLUMN auth_version bigint NOT NULL DEFAULT 1
    CONSTRAINT ck_user_auth_version CHECK (auth_version > 0);

-- 组件内部主键为 identity；业务关联始终是授权事实来源。
CREATE TABLE casbin_rule (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ptype varchar(100) NOT NULL,
    v0 varchar(255) NOT NULL DEFAULT '', v1 varchar(255) NOT NULL DEFAULT '',
    v2 varchar(255) NOT NULL DEFAULT '', v3 varchar(255) NOT NULL DEFAULT '',
    v4 varchar(255) NOT NULL DEFAULT '', v5 varchar(255) NOT NULL DEFAULT '',
    CONSTRAINT uk_casbin_rule UNIQUE(ptype, v0, v1, v2, v3, v4, v5),
    CONSTRAINT ck_casbin_ptype CHECK (ptype IN ('p', 'g'))
);

COMMIT;
